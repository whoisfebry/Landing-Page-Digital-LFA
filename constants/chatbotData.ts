function normalizeText(text: string): string {
    return text
        .toLowerCase()
        .normalize("NFKC")
        .replace(/[^\p{L}\p{N}\s]/gu, " ")
        .replace(/\s+/g, " ")
        .trim();
}

function matchesKeyword(message: string, keyword: string): boolean {
    const normalizedMessage = normalizeText(message);
    const normalizedKeyword = normalizeText(keyword);

    if (!normalizedMessage || !normalizedKeyword) {
        return false;
    }

    return ` ${normalizedMessage} `.includes(` ${normalizedKeyword} `);
}

export function getChatbotAnswer(message: string): string {
    const normalizedMessage = normalizeText(message);

    if (!normalizedMessage) {
        return "Silakan tuliskan pertanyaan yang ingin kamu ketahui tentang Digital LFA.";
    }

    // Sapaan
    if (
        /^(halo|hai|hi|hello|hei|hallo|assalamualaikum|pagi|siang|sore|malam)$/.test(
            normalizedMessage
        )
    ) {
        return "Halo! 👋 Saya Asisten Digital LFA. Saya siap membantu menjawab pertanyaan seputar Digital LFA, tahapan program, peran SKK Migas dan KKKS, serta manfaat program bagi masyarakat.";
    }

    if (
        /\b(selamat pagi|pagi)\b/.test(normalizedMessage)
    ) {
        return "Selamat pagi! 👋 Saya Asisten Digital LFA. Ada yang ingin kamu ketahui tentang Digital LFA?";
    }

    if (
        /\b(selamat siang|siang)\b/.test(normalizedMessage)
    ) {
        return "Selamat siang! 👋 Saya Asisten Digital LFA. Silakan tanyakan hal yang ingin kamu ketahui.";
    }

    if (
        /\b(selamat sore|sore)\b/.test(normalizedMessage)
    ) {
        return "Selamat sore! 👋 Saya Asisten Digital LFA. Ada yang bisa saya bantu?";
    }

    if (
        /\b(selamat malam|malam)\b/.test(normalizedMessage)
    ) {
        return "Selamat malam! 👋 Saya Asisten Digital LFA. Silakan tanyakan hal seputar Digital LFA.";
    }

    // Identitas chatbot
    if (
        /\b(siapa kamu|nama kamu|namamu|kamu siapa|nama chatbot|nama asisten)\b/.test(
            normalizedMessage
        )
    ) {
        return "Saya Asisten Digital LFA, chatbot yang membantu memberikan informasi seputar sistem Digital LFA dan program Pengembangan dan Pemberdayaan Masyarakat.";
    }

    // Kemampuan chatbot
    if (
        /\b(bisa bantu|bisa apa|apa yang bisa kamu|apa yang bisa dibantu|bantuan)\b/.test(
            normalizedMessage
        )
    ) {
        return "Saya bisa membantu menjelaskan pengertian dan tujuan Digital LFA, tahapan program, peran SKK Migas dan KKKS, indikator keberhasilan, anggaran, serta manfaat program bagi masyarakat. Silakan pilih pertanyaan yang tersedia atau tuliskan pertanyaanmu.";
    }

    if (
        /\b(apa kabar|gimana kabar|bagaimana kabar)\b/.test(
            normalizedMessage
        )
    ) {
        return "Saya siap membantu! 😊 Apa yang ingin kamu ketahui tentang Digital LFA?";
    }

    if (
        /\b(terima kasih|makasih|thanks|thank you|trims)\b/.test(
            normalizedMessage
        )
    ) {
        return "Sama-sama! 😊 Semoga informasi tentang Digital LFA membantu. Silakan tanyakan hal lain jika masih ada yang ingin diketahui.";
    }

    if (
        /\b(bye|dadah|sampai jumpa|selamat tinggal)\b/.test(
            normalizedMessage
        )
    ) {
        return "Sampai jumpa! 👋 Terima kasih telah menggunakan Asisten Digital LFA.";
    }

    // Cocokkan pertanyaan dengan kata kunci terpanjang terlebih dahulu.
    const sortedItems = [...chatbotData].sort((a, b) => {
        const maxLengthA = Math.max(...a.keywords.map((item) => normalizeText(item).length));
        const maxLengthB = Math.max(...b.keywords.map((item) => normalizeText(item).length));

        return maxLengthB - maxLengthA;
    });

    const matchedItem = sortedItems.find((item) =>
        item.keywords.some((keyword) =>
            matchesKeyword(normalizedMessage, keyword)
        )
    );

    if (matchedItem) {
        return matchedItem.answer;
    }

    return "Maaf, saya belum menemukan jawaban yang sesuai dengan pertanyaan tersebut. 😊 Kamu bisa bertanya tentang pengertian Digital LFA, tahapan program, SKK Migas, KKKS, anggaran, indikator keberhasilan, atau manfaat program bagi masyarakat.";
}